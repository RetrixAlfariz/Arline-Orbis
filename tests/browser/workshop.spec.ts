import {test,expect,type Page} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const open=async(page:Page)=>{await page.getByText('Tools',{exact:true}).click();await page.getByRole('button',{name:'Generation Workshop',exact:true}).click();};
const preview=(page:Page)=>page.getByTestId('workshop-preview');

test('drafts, recipes, stages, comparisons and minimization never change the committed world',async({page})=>{
  test.setTimeout(90000);await page.goto('/');
  const before=await page.getByTestId('elevation').innerText();
  await open(page);await expect(preview(page)).toContainText('180 × 91');
  await expect(page.getByRole('button',{name:'Apply reviewed world',exact:true})).toBeDisabled();
  await page.getByLabel('World recipe',{exact:true}).selectOption('Archipelago');
  await expect(page.getByLabel('Workshop plate count')).toHaveValue('24');
  await page.getByLabel('Workshop plate count').fill('23');
  await expect(page.getByLabel('World recipe',{exact:true})).toHaveValue('Custom');
  await page.getByLabel('Workshop seed').fill('workshop-candidates');
  await expect(preview(page)).toContainText('180 × 91');
  await page.getByRole('button',{name:'Compare three seeds',exact:true}).click();
  await expect(page.locator('.seed-candidates img')).toHaveCount(3,{timeout:30000});
  await page.getByRole('button',{name:'Select candidate 2',exact:true}).click();
  await expect(page.locator('.generation-stages button').filter({hasText:'Tectonics'})).toBeEnabled();
  await page.locator('.generation-stages button').filter({hasText:'Tectonics'}).click();
  await expect(page.locator('.generation-preview-banner')).toContainText('Tectonics');
  await expect(page.getByLabel('Preview layer',{exact:true})).toHaveText('Tectonic plates');
  await expect(page.getByLabel('Geographic system layer')).toHaveCount(0);
  await page.locator('.workshop-nav button').filter({hasText:'Review'}).click();
  await expect(page.getByLabel('Preview layer',{exact:true})).toHaveText('Surface relief');
  await expect(page.getByLabel('Generation parameters',{exact:true})).toBeHidden();
  await expect(page.getByRole('button',{name:'Generate final',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Minimize Generation Workshop',exact:true}).click();
  await expect(page.getByRole('button',{name:'Restore Generation Workshop',exact:true})).toBeVisible();
  await expect(page.locator('.generation-preview-banner')).toBeVisible();
  await page.getByRole('button',{name:'Restore Generation Workshop',exact:true}).click();
  await page.getByRole('button',{name:'Return to world',exact:true}).click();
  await expect(page.getByTestId('elevation')).toHaveText(before);
  await expect(page.locator('.generation-preview-banner')).toHaveCount(0);
});

test('final regional generation preserves the legacy base and round trips version 4 with undo',async({page,context})=>{
  test.setTimeout(120000);await page.goto('/');await open(page);
  await page.getByRole('button',{name:'Replace region',exact:true}).click();
  await expect(page.getByTestId('replacement-boundary')).toHaveCount(1);
  await page.getByLabel('Workshop seed').fill('regional-review');
  await page.getByLabel('Replacement radius').fill('1200');
  await page.getByRole('button',{name:'Generate final',exact:true}).click();
  await expect(preview(page)).toContainText('Final result',{timeout:60000});
  await expect(preview(page)).toContainText('720 × 361');
  await page.getByRole('button',{name:'Apply reviewed world',exact:true}).click();
  await expect(page.locator('.generation-preview-banner')).toHaveCount(0);
  await expect(page.getByText('Saved locally',{exact:true})).toBeVisible();
  const originalTerrain=await page.getByTestId('elevation').innerText();
  await page.getByRole('button',{name:'Sculpt terrain',exact:true}).click();
  await page.getByRole('button',{name:'Apply at selection',exact:true}).click();
  await expect(page.getByTestId('elevation')).not.toHaveText(originalTerrain);
  await page.getByRole('button',{name:'Remove last',exact:true}).click();
  await expect(page.getByTestId('elevation')).toHaveText(originalTerrain);
  await page.getByRole('button',{name:'Sculpt ON',exact:true}).click();
  const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Export',exact:true}).click();
  const file=(await(await pending).path())!;
  const p=JSON.parse(await readFile(file,'utf8'));
  expect(p.version).toBe(4);expect(p.planet.algorithm_version).toBe('m0-sample-v1');expect(p.regional_replacements).toHaveLength(1);
  const altitude=await page.getByTestId('elevation').innerText();await page.reload();
  await expect(page.getByTestId('elevation')).toHaveText(altitude,{timeout:30000});
  await page.getByRole('button',{name:'Import',exact:true}).click();
  await page.getByLabel('Import project file').setInputFiles(file);
  await expect(page.getByText('Saved locally',{exact:true})).toBeVisible();
  const compressed=page.waitForEvent('download');await page.getByRole('button',{name:'Export compressed .orbis',exact:true}).click();
  const bytes=await readFile((await(await compressed).path())!);
  if(process.env.ORBIS_E2E_PREVIEW){
    await expect(page.getByText('Offline ready',{exact:true})).toBeVisible();await context.setOffline(true);await page.reload();
    await expect(page.getByTestId('elevation')).toHaveText(altitude,{timeout:30000});
  }
  await page.getByLabel('Import project file').setInputFiles({name:'regional.orbis',mimeType:'application/gzip',buffer:bytes});
  await expect(page.getByText('Saved locally',{exact:true})).toBeVisible();
  await context.setOffline(false);
  await open(page);await page.getByText('Saved regional replacements (1)',{exact:true}).click();
  await page.getByRole('button',{name:'Remove in preview',exact:true}).click();
  await page.getByRole('button',{name:'Generate final',exact:true}).click();
  await expect(preview(page)).toContainText('Final result',{timeout:60000});
  await page.getByRole('button',{name:'Apply reviewed world',exact:true}).click();
  await page.getByRole('button',{name:'Undo last edit',exact:true}).click();
  await expect(page.getByTestId('elevation')).toHaveText(altitude);
});

test('locked regional content is blocked, stale finals are invalidated, and high-detail work cancels',async({page})=>{
  test.setTimeout(90000);await page.goto('/');
  await page.getByLabel('Landmark name',{exact:true}).fill('Protected summit');
  await page.getByRole('button',{name:'Set landmark',exact:true}).click();
  await page.getByRole('button',{name:'Lock landmark',exact:true}).click();
  await open(page);await page.getByRole('button',{name:'Replace region',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('locked content');
  await page.getByRole('button',{name:'Whole world',exact:true}).click();
  await page.getByRole('button',{name:'Generate final',exact:true}).click();
  await expect(preview(page)).toContainText('Final result',{timeout:30000});
  await page.locator('.workshop-nav button').filter({hasText:'Parameters'}).click();
  await page.getByLabel('Workshop seed').fill('newer-settings');
  await expect(page.getByRole('button',{name:'Apply reviewed world',exact:true})).toBeDisabled();
  await page.getByLabel('Workshop detail').selectOption('1440');
  await page.getByRole('button',{name:'Generate final',exact:true}).click();
  await page.getByRole('button',{name:'Cancel generation',exact:true}).click();
  await expect(page.getByRole('button',{name:'Apply reviewed world',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Return to world',exact:true}).click();
  await expect(page.getByRole('button',{name:'Unlock landmark',exact:true})).toBeVisible();
});
