import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
const exportWorld = async (page: Page) => {
  await page.getByText('File', { exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export project', exact: true }).click();
  return JSON.parse(await readFile((await (await download).path())!, 'utf8'));
};
test('seeded caves review, inspect, discard, preserve locked entrances and round trip', async ({ page }) => {
  test.setTimeout(90000); await page.goto('/');
  await page.getByRole('button', { name: 'Underground', exact: true }).click();
  await page.getByLabel('Cave node name', { exact: true }).fill('Protected gate');
  await page.getByLabel('Cave node kind', { exact: true }).selectOption('entrance');
  await page.getByLabel('Cave depth below ground (m)', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Save underground node', exact: true }).click();
  await page.getByRole('button', { name: 'Lock node', exact: true }).click();
  const original = (await exportWorld(page)).caves.nodes[0];
  await page.getByLabel('Underground generation anchor', { exact: true }).selectOption(original.id);
  await page.getByLabel('Underground generation seed', { exact: true }).fill('passage-review');
  await page.getByLabel('Generated chamber count', { exact: true }).fill('8');
  await page.getByLabel('Generated minimum depth (m)', { exact: true }).fill('100');
  await page.getByLabel('Generated maximum depth (m)', { exact: true }).fill('300');
  await page.getByLabel('Generated chamber radius (m)', { exact: true }).fill('40');
  await page.getByRole('button', { name: 'Generate underground preview', exact: true }).click();
  await expect(page.getByTestId('underground-generation-preview')).toContainText('8 chambers');
  await expect(page.getByTestId('cave-preview-node')).toHaveCount(8);
  await page.getByRole('button', { name: 'Inspect cave Chamber 1', exact: true }).click();
  await expect(page.getByTestId('cave-preview-inspection')).toContainText('Depth');
  expect((await exportWorld(page)).caves.nodes).toEqual([original]);
  const geometry = () => page.getByTestId('cave-section').evaluate(el => Array.from(el.querySelectorAll('line,ellipse')).map(shape =>
    ['x1','x2','y1','y2','cx','cy','rx','ry'].map(name => shape.getAttribute(name))));
  const first = await geometry();
  await page.getByRole('button', { name: 'Discard underground preview', exact: true }).click();
  await expect(page.getByTestId('cave-preview-node')).toHaveCount(0);
  await page.getByRole('button', { name: 'Generate underground preview', exact: true }).click();
  await expect(page.getByTestId('cave-preview-node')).toHaveCount(8);
  expect(await geometry()).toEqual(first);
  await page.getByLabel('Generated chamber count', { exact: true }).fill('9');
  await expect(page.getByRole('button', { name: 'Apply underground network', exact: true })).toBeDisabled();
  await page.getByLabel('Generated chamber count', { exact: true }).fill('8');
  await page.getByRole('button', { name: 'Generate underground preview', exact: true }).click();
  await expect(page.getByTestId('cave-preview-node')).toHaveCount(8);
  await page.getByRole('button', { name: 'Local 3D cave', exact: true }).click();
  await expect(page.locator('.cave-scene canvas')).toBeVisible();
  await page.getByRole('button', { name: 'Apply underground network', exact: true }).click();
  const applied = await exportWorld(page);
  expect(applied.caves.nodes).toHaveLength(9); expect(applied.caves.edges).toHaveLength(8);
  expect(applied.caves.nodes[0]).toEqual(original);
  await page.getByRole('button', { name: 'Generate underground preview', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already applied');
  await page.reload(); await page.getByRole('button', { name: 'Underground', exact: true }).click();
  expect((await exportWorld(page)).caves).toEqual(applied.caves);
  await page.getByLabel('Import project file').setInputFiles({ name: 'caves.orbis.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(applied)) });
  expect((await exportWorld(page)).caves).toEqual(applied.caves);
});

test('motion honors reduced motion and input interrupts camera travel', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto('/');
  const panel = page.locator('[data-panel=inspector]');
  expect(await panel.evaluate(el => getComputedStyle(el).animationName)).toBe('none');
  await page.getByRole('button', { name: '3D Globe', exact: true }).click();
  await expect(page.locator('.globe canvas')).toBeVisible();
  await page.getByRole('button', { name: /Lantern ridge/ }).click();
  const canvas = page.locator('.globe canvas'), box = (await canvas.boundingBox())!;
  await canvas.click({ position: { x: box.width / 2, y: box.height / 2 } });
  await expect(page.getByTestId('latitude')).toHaveText('-15.0000°');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: /Crown mountain/ }).click();
  await canvas.click({ position: { x: box.width / 2, y: box.height / 2 } });
  await expect(page.getByTestId('latitude')).toHaveText('30.0000°');
});
