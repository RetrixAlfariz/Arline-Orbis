import { test,expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('M5 detail controls review and apply explicitly, preserve locks, and replay after import/reload',async({page})=>{
  test.setTimeout(90000);await page.goto('/');
  await page.getByLabel('Landmark name',{exact:true}).fill('Protected atlas anchor');
  await page.getByLabel('Authored elevation (m)',{exact:true}).fill('4800');
  await page.getByRole('button',{name:'Set landmark',exact:true}).click();
  await page.getByRole('button',{name:'Lock landmark',exact:true}).click();
  await page.getByRole('navigation',{name:'Studio navigation'}).getByRole('button',{name:'Terrain',exact:true}).click();
  const workshop=page.locator('.generation-workshop');
  await expect(page.getByLabel('Workshop algorithm',{exact:true})).toHaveValue('m5-continuous-v1');
  await workshop.getByText('Terrain-specific detail',{exact:true}).click();
  await page.getByLabel('Workshop Broad hills',{exact:true}).fill('150');
  await page.getByLabel('Workshop Mountain crests',{exact:true}).fill('1200');
  await page.getByLabel('Workshop Fine mountain relief',{exact:true}).fill('100');
  await page.getByLabel('Workshop detail',{exact:true}).selectOption('1440');
  await page.getByRole('button',{name:'Generate final',exact:true}).click();
  await expect(page.getByTestId('workshop-preview')).toContainText('Final result',{timeout:60000});
  await expect(page.getByRole('button',{name:'Apply reviewed world',exact:true})).toBeDisabled();
  await page.getByLabel('Accept workshop terrain changes',{exact:true}).check();
  await page.getByRole('button',{name:'Apply reviewed world',exact:true}).click();
  await expect(page.getByTestId('elevation')).toHaveText('+4,800 m');
  await expect(page.getByRole('button',{name:'Update landmark',exact:true})).toBeDisabled();
  const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Export',exact:true}).click();
  const raw=await readFile((await(await pending).path())!,'utf8'),saved=JSON.parse(raw);
  expect(saved.planet.algorithm_version).toBe('m5-continuous-v1');
  expect(saved.generation_options).toMatchObject({resolution:1440,hill_detail_m:150,mountain_detail_m:1200,rock_detail_m:100});
  expect(saved.landmarks[0]).toMatchObject({locked:true,position:{lat_deg:30,lon_deg:-55,altitude_m:4800}});
  await page.reload();await expect(page.getByLabel('Geographic system layer',{exact:true})).toBeVisible({timeout:30000});
  await expect(page.getByTestId('elevation')).toHaveText('+4,800 m');
  await page.getByLabel('Import project file').setInputFiles({name:'continuous.orbis.json',mimeType:'application/json',buffer:Buffer.from(raw)});
  await expect(page.getByRole('button',{name:'Unlock landmark',exact:true})).toBeVisible();
  await expect(page.getByTestId('elevation')).toHaveText('+4,800 m');
});
