import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const out = 'docs/design/celestial-studio'; await mkdir(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
await page.goto('http://127.0.0.1:4180');
await page.getByRole('button', { name: 'Underground', exact: true }).click();
await page.getByRole('button', { name: 'Generate underground preview', exact: true }).click();
await page.getByTestId('underground-generation-preview').waitFor();
await page.waitForTimeout(350);
await page.screenshot({ path: `${out}/underground-controls.png` });
await page.getByRole('button', { name: 'Inspect cave Chamber 1', exact: true }).click();
await page.waitForTimeout(350);
await page.getByTestId('cave-section').screenshot({ path: `${out}/underground-section.png` });
await page.getByRole('button', { name: 'Local 3D cave', exact: true }).click();
await page.locator('.cave-scene canvas').waitFor();
await page.waitForTimeout(350);
await page.locator('.cave-scene').screenshot({ path: `${out}/underground-3d.png` });
await browser.close(); console.log('Underground previews captured.');
