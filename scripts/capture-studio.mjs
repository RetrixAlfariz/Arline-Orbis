import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const output = new URL('../docs/design/celestial-studio/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
await page.goto(process.env.ORBIS_PREVIEW_URL || 'http://127.0.0.1:4180');
await page.getByRole('button', { name: 'Set landmark', exact: true }).waitFor();
await page.screenshot({ path: `${output}/atlas.png` });
await page.getByRole('navigation', { name: 'Studio navigation' }).getByRole('button', { name: 'Globe', exact: true }).click();
await page.locator('.globe canvas').waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${output}/globe.png` });
await page.getByRole('navigation', { name: 'Studio navigation' }).getByRole('button', { name: 'Terrain', exact: true }).click();
await page.getByTestId('workshop-preview').filter({ hasText: '180 × 91' }).waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${output}/workshop.png` });
await page.getByRole('button', { name: 'Return to world', exact: true }).click();
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('navigation', { name: 'Studio navigation' }).getByRole('button', { name: 'Atlas', exact: true }).click();
await page.getByRole('button', { name: 'Close Inspector', exact: true }).click();
await page.screenshot({ path: `${output}/mobile.png` });
console.log(`Screenshots saved to ${output}`);
await browser.close();
